using System.Data.Common;
using System.Text;
using DbDelta.Core.Diff;

namespace DbDelta.Core.ScriptGen;

/// <summary>
/// Composes a deployment-ready T-SQL script for a user-selected subset of
/// <see cref="DifferencePair"/> objects. The generated script includes a
/// descriptive header (timestamp, source / target endpoints) followed by the
/// DDL body produced by the topologically ordered emitter pipeline already
/// implemented in <see cref="ScriptGenerator"/>.
/// </summary>
public static class DeployScriptBuilder
{
    private static readonly ScriptGenerator _generator = new();

    /// <summary>
    /// Builds the alignment script for <paramref name="selectedPairs"/>.
    /// </summary>
    /// <param name="fullResult">
    /// The COMPLETE comparison result, Identical pairs included — not a
    /// projection of the selection. Several passes in
    /// <see cref="ScriptGenerator"/> rescue objects the user cannot select:
    /// a trigger that is Identical on both sides is destroyed by the
    /// <c>DROP TABLE</c> of a rebuilt parent, and a foreign key held by an
    /// Identical table blocks the <c>DROP TABLE</c> of the table it points at.
    /// Those passes scan <c>fullResult.Differences</c>, so wrapping the
    /// selection in a synthetic result made every one of them a no-op on this
    /// path — a silently lost production trigger with a success verdict.
    /// </param>
    /// <param name="selectedPairs">
    /// The pairs selected by the user in the grid: what to emit DDL for. Passed
    /// to <see cref="ScriptGenerator.Generate"/> as the <c>selection</c>, which
    /// is exactly how the CLI drives it.
    /// </param>
    /// <param name="sourceEndpointSummary">
    /// Label for the source endpoint. A full connection string is accepted and
    /// reduced to server + database — see <see cref="DescribeEndpoint"/>.
    /// </param>
    /// <param name="targetEndpointSummary">Same, for the target endpoint.</param>
    /// <param name="nowUtc">The UTC timestamp to embed in the header.</param>
    /// <param name="dependencies">
    /// Source-side dependency edges. Deliberately has no default: passing none
    /// is not cosmetic — the topological sort then degenerates to
    /// kind-then-alphabetical order, so a new view that selects from a new
    /// function emits first and the deploy fails with Msg 208. A caller with
    /// nothing to pass has to say so with an empty list.
    /// </param>
    public static string Build(
        ComparisonResult fullResult,
        IReadOnlyList<DifferencePair> selectedPairs,
        string sourceEndpointSummary,
        string targetEndpointSummary,
        DateTime nowUtc,
        IReadOnlyList<Dependency.DependencyEdge> dependencies)
    {
        ArgumentNullException.ThrowIfNull(fullResult);
        ArgumentNullException.ThrowIfNull(selectedPairs);
        ArgumentNullException.ThrowIfNull(dependencies);

        StringBuilder header = new();
        header.AppendLine("-- ============================================================");
        header.AppendLine($"-- DbDelta alignment script");
        header.AppendLine($"-- Generated : {nowUtc:yyyy-MM-dd HH:mm:ss} UTC");
        header.AppendLine($"-- Source    : {DescribeEndpoint(sourceEndpointSummary)}");
        header.AppendLine($"-- Target    : {DescribeEndpoint(targetEndpointSummary)}");
        header.AppendLine($"-- Objects   : {selectedPairs.Count}");
        header.AppendLine("-- ============================================================");

        if (selectedPairs.Count == 0)
        {
            return header.ToString();
        }

        // Full result + selection, the same way the CLI calls it: `pairs` stays
        // the user's intent while the unfiltered scans over fullResult.Differences
        // can still see the Identical objects a rebuild or a DROP TABLE would
        // otherwise take down with it. We suppress the generator's bare
        // "-- Generated by DbDelta" line via DoNotOutputCommentHeader so our
        // descriptive header stands alone — no trimming, no orphaned GO. Keep
        // the Redgate-parity defaults.
        string body = _generator.Generate(
            fullResult,
            selection: selectedPairs,
            options: OptionsFor(selectedPairs),
            dependencies: dependencies);

        return header.ToString() + body;
    }

    /// <summary>
    /// Redgate-parity defaults, minus <c>IgnorePermissions</c> when the user
    /// explicitly selected a Permission row.
    /// </summary>
    /// <remarks>
    /// <c>IgnorePermissions</c> is part of <see cref="Options.ComparisonOptions.Default"/>,
    /// but the engine still <em>reports</em> Permission differences, so the grid
    /// offers them for selection. Leaving the flag on made the generator drop
    /// them silently: the script ran, reported success, and the difference was
    /// still there on the next compare. The selection IS the user's intent.
    /// </remarks>
    private static Options.ComparisonOptions OptionsFor(IReadOnlyList<DifferencePair> selectedPairs)
    {
        Options.ComparisonOptions options =
            Options.ComparisonOptions.Default | Options.ComparisonOptions.DoNotOutputCommentHeader;

        bool permissionSelected = selectedPairs.Any(
            p => string.Equals(p.Identity.Kind, "Permission", StringComparison.Ordinal));

        return permissionSelected
            ? options & ~Options.ComparisonOptions.IgnorePermissions
            : options;
    }

    /// <summary>
    /// Reduces an endpoint label to <c>server / database</c>, dropping every
    /// other token.
    /// </summary>
    /// <remarks>
    /// The two callers pass live connection strings, which carry the plaintext
    /// password — and this header is written to a <c>.sql</c> file that gets
    /// mailed around and committed. Deliberately an ALLOW-list of the two keys
    /// worth showing rather than a deny-list of secret-bearing ones: an
    /// unrecognised key is dropped instead of leaked. A label with no <c>=</c>
    /// at all is not a connection string and passes through unchanged.
    /// <para>
    /// Tokenising is delegated to <see cref="DbConnectionStringBuilder"/>, which
    /// knows the quoting rules. Splitting on <c>;</c> by hand did not: a value
    /// may legally contain a semicolon when quoted, so
    /// <c>Password="a;Server=hunter2"</c> tokenised into a truncated password
    /// and a <c>Server</c> key whose "value" was half the password — printed
    /// into the header as the server name. Unreachable from the setup dialog,
    /// reachable from the raw connection-string box and from the
    /// <c>{PASSWORD}</c> template substitution in the connection store.
    /// </para>
    /// </remarks>
    internal static string DescribeEndpoint(string endpointSummary)
    {
        if (string.IsNullOrWhiteSpace(endpointSummary)) { return "(non impostato)"; }
        if (!endpointSummary.Contains('=', StringComparison.Ordinal)) { return endpointSummary.Trim(); }

        DbConnectionStringBuilder parsed;
        try
        {
            parsed = new DbConnectionStringBuilder { ConnectionString = endpointSummary };
        }
        catch (ArgumentException)
        {
            // Not a parsable connection string. Say nothing rather than guess:
            // whatever is in there, some of it is probably a secret.
            return "(endpoint non riconosciuto)";
        }

        string? server = null;
        string? database = null;
        foreach (string key in parsed.Keys.OfType<string>())
        {
            string normalized = key.Replace(" ", string.Empty, StringComparison.Ordinal);
            string value = parsed[key]?.ToString()?.Trim() ?? string.Empty;
            if (value.Length == 0) { continue; }
            if (server is null && IsServerKey(normalized)) { server = value; }
            else if (database is null && IsDatabaseKey(normalized)) { database = value; }
        }

        return (server, database) switch
        {
            (null, null) => "(endpoint non riconosciuto)",
            (not null, null) => server,
            (null, not null) => $"? / {database}",
            _ => $"{server} / {database}",
        };
    }

    private static bool IsServerKey(string key) =>
        key.Equals("server", StringComparison.OrdinalIgnoreCase)
        || key.Equals("datasource", StringComparison.OrdinalIgnoreCase)
        || key.Equals("addr", StringComparison.OrdinalIgnoreCase)
        || key.Equals("address", StringComparison.OrdinalIgnoreCase)
        || key.Equals("networkaddress", StringComparison.OrdinalIgnoreCase);

    private static bool IsDatabaseKey(string key) =>
        key.Equals("database", StringComparison.OrdinalIgnoreCase)
        || key.Equals("initialcatalog", StringComparison.OrdinalIgnoreCase);
}
