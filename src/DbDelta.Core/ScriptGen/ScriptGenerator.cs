using System.Text;
using DbDelta.Core.Diff;

namespace DbDelta.Core.ScriptGen;

/// <summary>
/// Orchestrates per-object emitters and wraps the output in a deployment-ready batch.
/// v1 only registers <see cref="TableScriptEmitter"/>.
/// </summary>
public sealed class ScriptGenerator
{
    private readonly TableScriptEmitter _tableEmitter = new();

    /// <summary>
    /// Generates a complete T-SQL migration script for the given comparison result.
    /// </summary>
    /// <param name="result">The diff result from <see cref="ComparisonEngine"/>.</param>
    /// <param name="selection">Optional subset of pairs to include. Defaults to all differences.</param>
    /// <returns>A deployment-ready T-SQL batch string.</returns>
    public string Generate(ComparisonResult result, IEnumerable<DifferencePair>? selection = null)
    {
        ArgumentNullException.ThrowIfNull(result);
        IEnumerable<DifferencePair> pairs = selection ?? result.Differences;
        var sb = new StringBuilder();
        sb.AppendLine("-- Generated by DbDelta");
        sb.AppendLine("SET XACT_ABORT ON;");
        sb.AppendLine("BEGIN TRANSACTION;");
        sb.AppendLine("GO");

        foreach (DifferencePair pair in pairs)
        {
            if (pair.Status == DifferenceStatus.Identical)
            {
                continue;
            }

            sb.AppendLine(_tableEmitter.Emit(pair));
            sb.AppendLine("GO");
        }

        sb.AppendLine("COMMIT TRANSACTION;");
        sb.AppendLine("GO");
        return sb.ToString();
    }
}
